/**
 * Generates lib/search-index.generated.ts from the real catalog.
 *
 * Run with: bun scripts/generate-search-index.ts
 *
 * The generated module contains metadata only (id, title, category, tags,
 * description, path). It deliberately excludes React/HTML/CSS source so that
 * client components such as search do not pull the whole catalog into the
 * browser bundle.
 */

import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { effects, categories, getEffectSlug } from "../lib/effects-data";

// eslint-disable-next-line @typescript-eslint/no-explicit-any
const ROOT = join((import.meta as any).dir as string, "..");
const OUT = join(ROOT, "lib", "search-index.generated.ts");

interface SearchEntry {
  id: string;
  title: string;
  category: string;
  categoryTitle: string;
  description: string;
  tags: string[];
  path: string;
}

async function main() {
  const categoryTitle = new Map(categories.map((category) => [category.slug, category.title]));

  const entries: SearchEntry[] = effects.map((effect) => ({
    id: effect.id,
    title: effect.title,
    category: effect.category,
    categoryTitle: categoryTitle.get(effect.category) ?? effect.category,
    description: effect.description ?? "",
    tags: effect.tags ?? [],
    path: `/category/${effect.category}?effect=${getEffectSlug(effect)}`,
  }));

  const summaries = categories.map((category) => ({
    slug: category.slug,
    title: category.title,
    description: category.description,
    count: effects.filter((effect) => effect.category === category.slug).length,
  }));

  const content = `/* AUTO-GENERATED by scripts/generate-search-index.ts — do not edit by hand. */

export interface SearchEntry {
  id: string;
  title: string;
  category: string;
  categoryTitle: string;
  description: string;
  tags: string[];
  path: string;
}

export interface CategorySummary {
  slug: string;
  title: string;
  description: string;
  count: number;
}

export const searchEntries: SearchEntry[] = ${JSON.stringify(entries, null, 2)};

export const categorySummaries: CategorySummary[] = ${JSON.stringify(summaries, null, 2)};

export const catalogTotal = ${effects.length};
`;

  await writeFile(OUT, content, "utf-8");
  console.log(`[ok] Wrote ${OUT} (${entries.length} entries)`);
}

main().catch((error) => {
  console.error("Search index generation failed:", error);
  process.exit(1);
});
